export function buildSystemPrompt({ today = new Date() } = {}) {
  const date = today.toISOString().slice(0, 10);
  return `${BASE_PROMPT}

# 当前信息
今天是 ${date}。资料整理于 2026 年 11 月，之后的事你可能不知道，遇到时间相关的问题要留意这个边界。

${buildContextBlock()}`;
}

/** 只保留最近 N 轮，避免上下文无限膨胀。 */
export function trimHistory(history, maxTurns = 8) {
  if (!Array.isArray(history)) return [];
  const cleaned = history
    .filter((m) => m && (m.role === 'user' || m.role === 'assistant'))
    .filter((m) => typeof m.content === 'string' && m.content.trim())
    .map((m) => ({ role: m.role, content: m.content.trim().slice(0, 2000) }));
  const max = maxTurns * 2;
  return cleaned.length > max ? cleaned.slice(cleaned.length - max) : cleaned;
}

export function buildMessages({ system, history, question, maxTurns }) {
  return [
    { role: 'system', content: system },
    ...trimHistory(history, maxTurns),
    { role: 'user', content: String(question || '').trim().slice(0, 2000) },
  ];
}
